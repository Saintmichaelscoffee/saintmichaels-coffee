const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
 const context = await browser.newContext({viewport:{width:390,height:844}});
 const page = await context.newPage();
 await page.goto('http://localhost:8137/install.html');
 await page.evaluate(() => navigator.serviceWorker.ready);
 await page.reload();
 await page.waitForFunction(() => !!navigator.serviceWorker.controller);
 assert.equal(await page.locator('link[rel=manifest]').getAttribute('href'),'/manifest.webmanifest');
 assert.equal(await page.locator('[data-coffee-install]').isVisible(),false);
 await page.evaluate(() => {
  const event = new Event('beforeinstallprompt',{cancelable:true});
  event.prompt = async () => { window.promptCount = (window.promptCount || 0) + 1; };
  event.userChoice = Promise.resolve({outcome:'dismissed'});
  window.dispatchEvent(event);
 });
 assert.equal(await page.locator('[data-coffee-install]').isVisible(),true);
 await page.locator('[data-coffee-install]').click();
 assert.match(await page.locator('[data-coffee-install-status]').textContent(),/No problem/);
 assert.equal(await page.evaluate(() => window.promptCount),1);
 assert.equal(await page.locator('[data-coffee-install]').isVisible(),false);
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
 await page.screenshot({path:'/workspace/shared/customer-phone-app-install-mobile.png',fullPage:true});
 await page.goto('http://localhost:8137/shop.html');
 const originalTitle = await page.title();
 assert(!originalTitle.includes('offline'));
 const cached = await page.evaluate(async () => { const c = await caches.open('smc-coffee-offline-v1'); return (await c.keys()).map(r=>new URL(r.url).pathname); });
 assert.deepEqual(cached,['/offline.html']);
 await context.setOffline(true);
 await page.reload();
 assert.match(await page.title(),/offline/);
 assert.equal(await page.locator('form').count(),0);
 await context.setOffline(false);
 await page.locator('a').click();
 assert(! (await page.title()).includes('offline'));
 const manifest=await (await context.request.get('http://localhost:8137/manifest.webmanifest')).json();
 assert.equal(manifest.short_name,'SMC Coffee');
 for(const icon of manifest.icons) assert.equal((await context.request.get('http://localhost:8137'+icon.src)).status(),200);
 await browser.close();
 console.log('PASS: manifest/icons, 390px layout, opt-in prompt dismissal, single prompt, no form offline, only offline notice cached, offline fallback, online recovery.');
})().catch(e=>{console.error(e);process.exit(1)});
